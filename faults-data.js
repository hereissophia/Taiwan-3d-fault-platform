const DEG = Math.PI / 180;
const R_EARTH_LAT_M = 110540;

function computeStats(f) {
  const lats = f.coords.map((c) => c[1]);
  const lons = f.coords.map((c) => c[0]);
  const lat = lats.reduce((a, b) => a + b, 0) / lats.length;
  const lon = lons.reduce((a, b) => a + b, 0) / lons.length;
  const R = 6371;
  let len = 0;
  for (let i = 0; i < f.coords.length - 1; i++) {
    const [lon1, lat1] = f.coords[i], [lon2, lat2] = f.coords[i + 1];
    const dLat = (lat2 - lat1) * DEG, dLon = (lon2 - lon1) * DEG;
    const a = Math.sin(dLat / 2) ** 2 + Math.cos(lat1 * DEG) * Math.cos(lat2 * DEG) * Math.sin(dLon / 2) ** 2;
    len += R * 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
  }
  return { lat: +lat.toFixed(3), lon: +lon.toFixed(3), lengthKm: +len.toFixed(1) };
}

const AZ_LABEL = (deg) => {
  const dirs = ['北', '東北', '東', '東南', '南', '西南', '西', '西北'];
  return dirs[Math.round(((deg % 360) / 45)) % 8];
};

